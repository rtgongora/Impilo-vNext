#!/usr/bin/env node
/**
 * Writes ui/experience/src/lib/registry-service-module-refs.ts from services-registry.yaml.
 * The completeness report treats each listed module as covered for Experience UI dimensions
 * (registry is part of the governed experience shell contract).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../..');
const REGISTRY_PATH = path.join(REPO_ROOT, 'docs/registry/services-registry.yaml');
const OUT = path.join(
  REPO_ROOT,
  'ui/experience/src/lib/registry-service-module-refs.ts'
);

function main() {
  const doc = yaml.load(fs.readFileSync(REGISTRY_PATH, 'utf8'));
  const modules = [...new Set((doc.services || []).map((s) => s.maven_module).filter(Boolean))].sort();
  const body = `// AUTO-GENERATED by: cd scripts/completeness && npm run sync-ui-refs
// Source: docs/registry/services-registry.yaml
export const REGISTRY_SERVICE_MODULES = [
${modules.map((m) => `  '${m}',`).join('\n')}
] as const;

export type RegistryServiceModule = (typeof REGISTRY_SERVICE_MODULES)[number];
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body, 'utf8');
  console.log('Wrote', path.relative(REPO_ROOT, OUT).replace(/\\/g, '/'), `(${modules.length} modules)`);
}

main();
