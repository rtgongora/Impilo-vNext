#!/usr/bin/env node
/**
 * Writes services/experience-bff/src/main/resources/registry-downstream-services.yml
 * from docs/registry/services-registry.yaml (maven_module → default HTTP base URL).
 * Excludes experience-bff (no self HTTP hop). Regenerate after registry port changes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../..');
const REGISTRY_PATH = path.join(REPO_ROOT, 'docs/registry/services-registry.yaml');
const OUT = path.join(
  REPO_ROOT,
  'services/experience-bff/src/main/resources/registry-downstream-services.yml'
);

function main() {
  const doc = yaml.load(fs.readFileSync(REGISTRY_PATH, 'utf8'));
  const lines = [
    '# AUTO-GENERATED by: cd scripts/completeness && npm run sync-bff-downstreams',
    '# Source: docs/registry/services-registry.yaml',
    'impilo:',
    '  registry-downstream:',
    '    services:',
  ];
  for (const s of doc.services || []) {
    const mod = s.maven_module;
    if (!mod || mod === 'experience-bff') continue;
    const port = s.default_http_port;
    if (port == null) continue;
    lines.push(`      ${mod}: http://localhost:${port}`);
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');
  console.log('Wrote', path.relative(REPO_ROOT, OUT).replace(/\\/g, '/'));
}

main();
