#!/usr/bin/env node
/**
 * Emit SecurityConfig.java with TrustContextFilter for services that lack one.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRegistryServices } from './registry-services.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../..');
const SERVICES_DIR = path.join(REPO_ROOT, 'services');

const TARGETS = new Set([
  'channels-service',
  'dispatch-service',
  'referral-service',
  'rtc-gateway-service',
  'scheduling-service',
]);

function main() {
  const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const dryRun = process.argv.includes('--dry-run');
  let created = 0;

  for (const svc of loadRegistryServices()) {
    if (!TARGETS.has(svc.id) && only.length && !only.includes(svc.id)) continue;
    if (only.length && !only.includes(svc.id) && !TARGETS.has(svc.id)) continue;
    if (!TARGETS.has(svc.id) && !only.includes(svc.id)) continue;

    const modulePath = path.join(SERVICES_DIR, svc.maven_module);
    const pkg = resolveConfigPackage(modulePath);
    if (!pkg) continue;

    const outFile = path.join(modulePath, 'src/main/java', ...pkg.split('.'), 'SecurityConfig.java');
    if (fs.existsSync(outFile)) continue;

    const prop = svc.id.replace(/-service$/, '').replace(/-/g, '.');
    const content = template(pkg, prop);
    if (dryRun) {
      console.log(`would create ${path.relative(REPO_ROOT, outFile)}`);
    } else {
      fs.mkdirSync(path.dirname(outFile), { recursive: true });
      fs.writeFileSync(outFile, content, 'utf8');
      console.log(`created ${path.relative(REPO_ROOT, outFile)}`);
    }
    created++;
  }
  console.log(`emit-service-security-config: created=${created}${dryRun ? ' (dry-run)' : ''}`);
}

function resolveConfigPackage(modulePath) {
  const mainJava = path.join(modulePath, 'src/main/java');
  if (!fs.existsSync(mainJava)) return null;
  let appPkg = null;
  walk(mainJava, (file) => {
    if (!file.endsWith('Application.java')) return;
    const text = fs.readFileSync(file, 'utf8');
    const m = text.match(/^package\s+([\w.]+);/m);
    if (m) appPkg = `${m[1]}.config`;
  });
  return appPkg;
}

function walk(dir, fn) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, fn);
    else fn(p);
  }
}

function template(pkg, propKey) {
  return `package ${pkg};

import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.Customizer;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configuration.EnableWebSecurity;
import org.springframework.security.config.http.SessionCreationPolicy;
import org.springframework.security.web.SecurityFilterChain;
import org.springframework.security.web.authentication.UsernamePasswordAuthenticationFilter;
import zw.gov.mohcc.impilo.shared.auth.TrustContextFilter;

/** OAuth2 JWT + trust header extraction. Generated by emit-service-security-config.mjs */
@Configuration
@EnableWebSecurity
public class SecurityConfig {

    @Bean
    public TrustContextFilter trustContextFilter(ObjectMapper objectMapper) {
        return new TrustContextFilter(objectMapper);
    }

    @Bean
    public SecurityFilterChain filterChain(
            HttpSecurity http,
            TrustContextFilter trustContextFilter,
            @Value("\${${propKey}.security.oauth2-enabled:true}") boolean oauth2Enabled) throws Exception {
        http.csrf(csrf -> csrf.disable())
                .sessionManagement(sm -> sm.sessionCreationPolicy(SessionCreationPolicy.STATELESS))
                .addFilterBefore(trustContextFilter, UsernamePasswordAuthenticationFilter.class);

        if (oauth2Enabled) {
            http.authorizeHttpRequests(auth -> auth
                            .requestMatchers(
                                    "/actuator/health",
                                    "/actuator/health/**",
                                    "/actuator/info",
                                    "/actuator/prometheus",
                                    "/v3/api-docs/**",
                                    "/swagger-ui/**",
                                    "/swagger-ui.html"
                            ).permitAll()
                            .anyRequest().authenticated())
                    .oauth2ResourceServer(oauth2 -> oauth2.jwt(Customizer.withDefaults()));
        } else {
            http.authorizeHttpRequests(auth -> auth.anyRequest().permitAll());
        }
        return http.build();
    }
}
`;
}

main();
