#!/usr/bin/env node
/**
 * Facility-estate seed generator — durable, deterministic, reproducible.
 *
 * Reads the cleaned Zimbabwe Master Health Facility CSV (the governed/approved output of the
 * 2024-07-23 review) and emits Flyway seed migrations so the 1,773 facilities + their
 * coordinates survive a FULL_BOOT_CLEAN_REBUILD (they were previously loaded at runtime via
 * import-facility-master-pack.sh + a Tuso→Ndila sync, so a clean rebuild wiped them).
 *
 * Emits:
 *   services/tuso-service/src/main/resources/db/migration/V027__seed_master_health_facilities.sql
 *   services/ndila-service/src/main/resources/db/migration/<next>__seed_master_facility_locations.sql
 *
 * Determinism: facility_uuid = uuidv5(facility_code, IMPILO_FACILITY_NAMESPACE) — identical in
 * both DBs so Ndila locations join back to Tuso facilities. created_at pinned to the source
 * vintage (2024-07-23). Idempotent: Tuso ON CONFLICT (tenant_id, facility_code); Ndila NOT EXISTS.
 *
 * Usage: node scripts/seed/generate-facility-estate-seed.mjs
 * Source of truth: the CSV. Re-run after the CSV changes; commit the regenerated SQL.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CSV = join(REPO, "data/source/zimbabwe/master-health-facility/2024-07-23/clean_tuso_facility_import.csv");
const PUBLIC_TENANT = "00000000-0000-0000-0000-000000000001";
const PUBLIC_POD = "national-spine";
const SOURCE_LABEL = "MASTER_HEALTH_FACILITY_2024_07_23";
const SOURCE_TS = "2024-07-23T00:00:00Z";
// Fixed namespace UUID so facility_uuid is stable across DBs + re-runs.
const NS = "6f1c1b7e-2b3a-4c5d-9e8f-0a1b2c3d4e5f";

/** RFC-4122 v5 (SHA-1) UUID — deterministic from (namespace, name). */
function uuidv5(name, namespace) {
  const nsBytes = Buffer.from(namespace.replace(/-/g, ""), "hex");
  const hash = createHash("sha1").update(nsBytes).update(Buffer.from(name, "utf8")).digest();
  const b = hash.subarray(0, 16);
  b[6] = (b[6] & 0x0f) | 0x50; // version 5
  b[8] = (b[8] & 0x3f) | 0x80; // variant
  const h = b.toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

/** Minimal RFC-4180 CSV parser (handles quoted fields + embedded commas/quotes). */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field); rows.push(row); row = []; field = ""; }
    else if (c === "\r") { /* skip */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const sq = (v) => (v == null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null || v === "" || Number.isNaN(Number(v)) ? "NULL" : String(Number(v)));
/** Coordinate guard: NULL out non-finite or out-of-geographic-range values (source decimal-point
 * errors) rather than guessing — numeric(10,7) also can't hold |v|>=1000. Honest: unknown coords. */
const geo = (v) => {
  const n = Number(v);
  return v == null || v === "" || !Number.isFinite(n) || Math.abs(n) > 180 ? "NULL" : String(n);
};

const raw = readFileSync(CSV, "utf8").replace(/^﻿/, "");
const [header, ...lines] = parseCsv(raw).filter((r) => r.length > 1);
const col = Object.fromEntries(header.map((h, i) => [h.trim(), i]));

const STATUS_MAP = { ACTIVE_OR_OPERATIONAL: "ACTIVE", CLOSED: "CLOSED", INACTIVE: "INACTIVE" };

const facilities = [];
for (const r of lines) {
  const code = (r[col.facility_code] || "").trim();
  const name = (r[col.facility_name] || "").trim();
  if (!code || !name) continue; // never seed a codeless/nameless row (matches the import's safety rule)
  facilities.push({
    code,
    name,
    type: (r[col.facility_type_canonical] || "").trim() || null,
    province: (r[col.province] || "").trim() || null,
    district: (r[col.district] || "").trim() || null,
    lat: (r[col.latitude] || "").trim(),
    lon: (r[col.longitude] || "").trim(),
    ownership: (r[col.ownership_canonical] || "").trim() || null,
    level: (r[col.level_canonical] || "").trim() || null,
    status: STATUS_MAP[(r[col.status_canonical] || "").trim()] || "ACTIVE",
    beds: (r[col.bed_capacity] || "").trim(),
    uuid: uuidv5(code, NS),
  });
}

// ── Tuso facility seed ────────────────────────────────────────────────────────────────
const tHeader = `-- GENERATED by scripts/seed/generate-facility-estate-seed.mjs — do not hand-edit.
-- Durable seed of the ${facilities.length} cleaned Master Health Facilities (source: ${SOURCE_LABEL}).
-- Was runtime-loaded (import-facility-master-pack.sh) so a clean rebuild wiped it; this makes it durable.
-- Idempotent on UNIQUE (tenant_id, facility_code). regulatory_status stays DRAFT (not fabricating
-- regulatory approval) + provenance recorded in metadata; per-facility legitimacy/classification is a
-- separate governed enrichment. facility_uuid is a deterministic uuidv5(facility_code).
`;
const tValues = facilities.map((f) => {
  const meta = `jsonb_build_object('sourceLabel','${SOURCE_LABEL}','facilitySetupState','IMPORTED_PENDING_CONFIGURATION','seededBy','facility-estate-seed'${f.beds ? `,'bedCapacity',${num(f.beds)}` : ""})`;
  return `  (${sq(PUBLIC_TENANT)}, ${sq(f.code)}, ${sq(f.name)}, ${sq(f.type)}, ${sq(f.province)}, ${sq(f.district)}, ${geo(f.lat)}, ${geo(f.lon)}, ${sq(f.status)}, ${sq(f.ownership)}, ${sq(f.level)}, ${sq(f.uuid)}::uuid, 'DRAFT', 1, ${meta}, '${SOURCE_TS}'::timestamptz)`;
}).join(",\n");
const tSql = `${tHeader}
INSERT INTO tuso.facility
  (tenant_id, facility_code, name, facility_type, province, district, latitude, longitude, status, ownership, level, facility_uuid, regulatory_status, version, metadata, created_at)
VALUES
${tValues}
ON CONFLICT (tenant_id, facility_code) DO UPDATE SET
  name = EXCLUDED.name, facility_type = EXCLUDED.facility_type, province = EXCLUDED.province,
  district = EXCLUDED.district, latitude = EXCLUDED.latitude, longitude = EXCLUDED.longitude,
  status = EXCLUDED.status, ownership = EXCLUDED.ownership, level = EXCLUDED.level,
  metadata = tuso.facility.metadata || EXCLUDED.metadata, updated_at = now();
`;
writeFileSync(join(REPO, "services/tuso-service/src/main/resources/db/migration/V027__seed_master_health_facilities.sql"), tSql);

// ── Ndila location seed ───────────────────────────────────────────────────────────────
const geoFac = facilities.filter((f) => geo(f.lat) !== "NULL" && geo(f.lon) !== "NULL");
const nHeader = `-- GENERATED by scripts/seed/generate-facility-estate-seed.mjs — do not hand-edit.
-- Durable seed of ${geoFac.length} facility LOCATIONS (of ${facilities.length} facilities; rest lack coordinates).
-- Mirrors the Tuso→Ndila master sync (NdilaFacilityMasterSyncService) as a durable seed so spatial
-- search (nearest/nearby/ETA) survives a clean rebuild. owner_entity_id = facility_code links back to
-- Tuso (whose facilities also carry their own lat/lon). Idempotent via NOT EXISTS.
`;
const nValues = geoFac.map((f) =>
  `  (${sq(PUBLIC_TENANT)}, ${sq(PUBLIC_POD)}, 'tuso-service', 'FACILITY', ${sq(f.code)}, ${sq(f.name)}, 'FACILITY', ${geo(f.lat)}, ${geo(f.lon)}, ${sq(f.district)}, ${sq(f.province)}, 'ZWE')`
).join(",\n");
// Note: column list validated against ndila_locations (id/created/updated have defaults).
// owner_entity_id = facility_code is the stable Tuso link (Tuso facilities also carry their own
// lat/lon, so find-care distance works off Tuso directly; this feeds Ndila's dedicated spatial API).
const nSql = `${nHeader}
INSERT INTO ndila_locations
  (tenant_id, pod_id, owner_service, owner_entity_type, owner_entity_id, name, location_type, latitude, longitude, district, province, country)
SELECT v.tenant_id::uuid, v.pod_id, v.owner_service, v.owner_entity_type, v.owner_entity_id, v.name, v.location_type, v.latitude::numeric, v.longitude::numeric, v.district, v.province, v.country
FROM (VALUES
${nValues}
) AS v(tenant_id, pod_id, owner_service, owner_entity_type, owner_entity_id, name, location_type, latitude, longitude, district, province, country)
WHERE NOT EXISTS (
  SELECT 1 FROM ndila_locations l
  WHERE l.owner_service = 'tuso-service' AND l.owner_entity_type = 'FACILITY' AND l.owner_entity_id = v.owner_entity_id
);
`;
writeFileSync(join(REPO, "services/ndila-service/src/main/resources/db/migration/V003__seed_master_facility_locations.sql"), nSql);

// ── Facility-capability baseline seed (unblocks service-aware find-care) ────────────────
// Type-inferred service package by facility tier — the standard MoH service scope per facility
// level. HONEST: zibo_validated=false + source=FACILITY_TYPE_BASELINE, so it is clearly a
// type-inferred baseline, not per-facility Zibo-verified. The find-care taxonomy matches these
// canonical codes (or their display names). Per-facility validation is a governed follow-up.
const CAP_NAME = {
  OPD: "General Outpatient", IMMUNIZATION: "Immunization", FAMILY_PLANNING: "Family Planning",
  HIV: "HIV Services", ART: "ART", TB: "TB Services", PHARMACY: "Pharmacy", MATERNITY: "Maternity",
  ANTENATAL: "Antenatal Care", PAEDIATRICS: "Paediatrics", OBSTETRICS: "Obstetrics", SURGERY: "Surgery",
  LABORATORY: "Laboratory", RADIOLOGY: "Radiology", IMAGING: "Diagnostic Imaging", DENTAL: "Dental",
  MENTAL_HEALTH: "Mental Health", EMERGENCY: "Emergency", ULTRASOUND: "Ultrasound",
  OPHTHALMOLOGY: "Ophthalmology", PSYCHIATRY: "Psychiatry", DIABETES: "Diabetes Care", RENAL: "Renal",
  CHRONIC_CARE: "Chronic Care", ONCOLOGY: "Oncology", DIALYSIS: "Dialysis", OPTICAL: "Optical",
};
const CLINIC = ["OPD", "IMMUNIZATION", "FAMILY_PLANNING", "HIV", "ART", "TB", "PHARMACY"];
const RHC = [...CLINIC, "MATERNITY", "ANTENATAL", "PAEDIATRICS"];
const HOSPITAL = [...RHC, "OBSTETRICS", "SURGERY", "LABORATORY", "RADIOLOGY", "IMAGING", "DENTAL", "MENTAL_HEALTH", "EMERGENCY"];
const PROVINCIAL = [...HOSPITAL, "ULTRASOUND", "OPHTHALMOLOGY", "PSYCHIATRY", "DIABETES", "RENAL", "CHRONIC_CARE", "ONCOLOGY"];
const CENTRAL = [...PROVINCIAL, "DIALYSIS", "OPTICAL"];
const INFECTIOUS = ["OPD", "HIV", "ART", "TB", "LABORATORY", "PHARMACY"];
const TYPE_CAPS = {
  CLINIC, MISSION_CLINIC: CLINIC, PRIVATE_CLINIC: CLINIC, PRIVATE: CLINIC, PVT: CLINIC, HC: CLINIC,
  HEALTH_CENTRE: CLINIC, SCHOOL_DISPENSARY: CLINIC, SDA: CLINIC, MINE: CLINIC, MUNICIPALITY: CLINIC,
  UNIFORMED: CLINIC, ZPCS: CLINIC, UNIVERSITY: CLINIC, SCHOOL: CLINIC,
  RURAL_HEALTH_CENTRE: RHC,
  DISTRICT_HOSPITAL: HOSPITAL, RURAL_HOSPITAL: HOSPITAL, MISSION_HOSPITAL: HOSPITAL,
  PRIVATE_HOSPITAL: HOSPITAL, HOSPITAL_REQUIRES_LEVEL_REVIEW: HOSPITAL,
  PROVINCIAL_HOSPITAL: PROVINCIAL, CENTRAL_HOSPITAL: CENTRAL, INFECTIOUS_DISEASE_HOSPITAL: INFECTIOUS,
};
const capMapRows = [];
for (const [ftype, caps] of Object.entries(TYPE_CAPS)) {
  for (const code of caps) capMapRows.push(`  (${sq(ftype)}, ${sq(code)}, ${sq(CAP_NAME[code])})`);
}
const cSql = `-- GENERATED by scripts/seed/generate-facility-estate-seed.mjs — do not hand-edit.
-- Facility-capability BASELINE by facility tier (standard MoH service scope per level).
-- HONEST: zibo_validated=false + metadata.source='FACILITY_TYPE_BASELINE' — a type-inferred baseline,
-- NOT per-facility Zibo-verified. Unblocks service-aware find-care; per-facility validation is a
-- governed follow-up. Idempotent via NOT EXISTS. Only seeds the master-pack facilities.
INSERT INTO tuso.facility_capability
  (facility_id, tenant_id, capability_code, capability_type, name, zibo_validated, active, metadata, created_at)
SELECT f.id, f.tenant_id, m.code, 'CLINICAL_SERVICE', m.cname, false, true,
       jsonb_build_object('source','FACILITY_TYPE_BASELINE','facilityType',f.facility_type), '${SOURCE_TS}'::timestamptz
FROM tuso.facility f
JOIN (VALUES
${capMapRows.join(",\n")}
) AS m(ftype, code, cname) ON m.ftype = f.facility_type
WHERE f.tenant_id = ${sq(PUBLIC_TENANT)}
  AND (f.metadata->>'sourceLabel') = '${SOURCE_LABEL}'
  AND NOT EXISTS (SELECT 1 FROM tuso.facility_capability c WHERE c.facility_id = f.id AND c.capability_code = m.code);
`;
writeFileSync(join(REPO, "services/tuso-service/src/main/resources/db/migration/V028__seed_facility_capabilities.sql"), cSql);

console.log(`facilities parsed: ${facilities.length}`);
console.log(`  with coordinates: ${geoFac.length}`);
console.log(`  capability map rows: ${capMapRows.length} (across ${Object.keys(TYPE_CAPS).length} facility types)`);
console.log(`  tuso seed  -> services/tuso-service/.../V027__seed_master_health_facilities.sql (${(tSql.length / 1024).toFixed(0)} KB)`);
console.log(`  ndila seed -> services/ndila-service/.../V003__seed_master_facility_locations.sql`);
