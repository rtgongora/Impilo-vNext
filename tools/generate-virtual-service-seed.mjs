#!/usr/bin/env node
/**
 * Generate the TUSO virtual-service registry seed migration from the canonical
 * virtual-hospital operating-model document.
 *
 * Source of truth: contracts/telemedicine/virtual-hospitals.json (the BFF
 * classpath copy at services/experience-bff/src/main/resources/telemedicine/
 * operating-model/virtual-hospitals.json is the served fallback and must stay
 * byte-identical — a drift test pins them together).
 *
 * Output (checked in): services/tuso-service/src/main/resources/db/migration/
 * V023__virtual_service_seed.sql
 *
 * Rules encoded here:
 *  - every entity seeds as lifecycle_status CONFIGURED (never ACTIVE — stored
 *    state must not overstate runtime reality);
 *  - routing seams come from currentRoutingSeams and seed active=TRUE (these
 *    are the entries already ROUTABLE_VIA_EXISTING_SEAMS);
 *  - queue definitions seed with default_sla_minutes NULL and rules '{}' —
 *    SLA values are governed configuration, never invented here.
 *
 * Usage: node tools/generate-virtual-service-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(REPO, "contracts/telemedicine/virtual-hospitals.json");
const BFF_COPY = path.join(
  REPO,
  "services/experience-bff/src/main/resources/telemedicine/operating-model/virtual-hospitals.json",
);
const OUTPUT = path.join(
  REPO,
  "services/tuso-service/src/main/resources/db/migration/V023__virtual_service_seed.sql",
);

/** Platform default tenant; per-tenant estates re-seed through governed import. */
const SEED_TENANT = "00000000-0000-0000-0000-000000000001";

const doc = JSON.parse(readFileSync(SOURCE, "utf8"));
const bffDoc = JSON.parse(readFileSync(BFF_COPY, "utf8"));
if (JSON.stringify(doc) !== JSON.stringify(bffDoc)) {
  console.error(
    "FATAL: contracts/telemedicine/virtual-hospitals.json and the BFF resource copy have drifted — reconcile before generating.",
  );
  process.exit(1);
}

const hospitals = doc.virtualHospitals;
if (!Array.isArray(hospitals) || hospitals.length === 0) {
  console.error("FATAL: no virtualHospitals entries in source document");
  process.exit(1);
}

const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const jb = (v) => `'${JSON.stringify(v ?? []).replace(/'/g, "''")}'::jsonb`;

const lines = [];
lines.push("-- ============================================================================");
lines.push("-- V023: Virtual service registry seed — GENERATED FILE, DO NOT EDIT BY HAND.");
lines.push("--");
lines.push("-- Generated by tools/generate-virtual-service-seed.mjs from the canonical");
lines.push("-- operating-model document contracts/telemedicine/virtual-hospitals.json.");
lines.push("-- Re-run the generator and check in the result when the document changes.");
lines.push("--");
lines.push(`-- Entities: ${hospitals.length} (all seeded CONFIGURED — activation is a governed,`);
lines.push("-- fail-closed runtime transition, never a seed default). Routing seams for the");
lines.push("-- entries already routable via existing teleconsult substrate seed active=TRUE.");
lines.push("-- Queue definitions seed WITHOUT SLA values (governed configuration only).");
lines.push("-- ============================================================================");
lines.push("");

let seamCount = 0;
let activeSeamCount = 0;
let queueDefCount = 0;

for (const vh of hospitals) {
  lines.push(`-- ---- ${vh.id}: ${vh.name} ----`);
  lines.push(
    "INSERT INTO tuso.virtual_service_entity (" +
      "vs_uid, tenant_id, name, level, operating_model, operating_authority, " +
      "regulatory_status, purpose, catchment, province_code, cross_border_participation, " +
      "allowed_cross_border_privileges, billing_models, session_mode_ids, " +
      "provider_pool_cadres, linked_facility_roles, lifecycle_status) VALUES (",
  );
  lines.push(
    [
      q(vh.id),
      `'${SEED_TENANT}'`,
      q(vh.name),
      q(vh.level),
      q(vh.operatingModel),
      q(vh.operatingAuthority),
      q(vh.regulatoryStatus),
      q(vh.purpose),
      q(vh.catchment),
      q(vh.provinceCode ?? null),
      vh.crossBorderParticipation ? "TRUE" : "FALSE",
      jb(vh.allowedCrossBorderPrivileges),
      jb(vh.billingModels),
      jb(vh.sessionModeIds),
      jb(vh.providerPoolCadres),
      jb(vh.linkedFacilityRoles),
      "'CONFIGURED'",
    ]
      .map((v) => "    " + v)
      .join(",\n"),
  );
  lines.push(") ON CONFLICT (vs_uid) DO NOTHING;");
  lines.push("");

  (vh.serviceLines ?? []).forEach((name, i) => {
    lines.push(
      "INSERT INTO tuso.virtual_service_line (virtual_service_id, name, position) " +
        `SELECT id, ${q(name)}, ${i} FROM tuso.virtual_service_entity WHERE vs_uid = ${q(vh.id)} ` +
        "AND NOT EXISTS (SELECT 1 FROM tuso.virtual_service_line l JOIN tuso.virtual_service_entity e " +
        `ON l.virtual_service_id = e.id WHERE e.vs_uid = ${q(vh.id)} AND l.name = ${q(name)});`,
    );
  });

  for (const seam of vh.currentRoutingSeams ?? []) {
    seamCount += 1;
    activeSeamCount += 1;
    lines.push(
      "INSERT INTO tuso.virtual_service_routing_seam (virtual_service_id, routing_type, target_ref, note, active) " +
        `SELECT id, ${q(seam.routingType)}, ${q(seam.targetRef)}, ${q(seam.note ?? null)}, TRUE ` +
        `FROM tuso.virtual_service_entity WHERE vs_uid = ${q(vh.id)} ` +
        "ON CONFLICT (virtual_service_id, routing_type, target_ref) DO NOTHING;",
    );
  }

  for (const queue of vh.queues ?? []) {
    queueDefCount += 1;
    lines.push(
      "INSERT INTO tuso.virtual_service_queue_def (virtual_service_id, queue_key, name, default_sla_minutes, rules) " +
        `SELECT id, ${q(queue.id)}, ${q(queue.name)}, NULL, '{}'::jsonb ` +
        `FROM tuso.virtual_service_entity WHERE vs_uid = ${q(vh.id)} ` +
        "ON CONFLICT (virtual_service_id, queue_key) DO NOTHING;",
    );
  }
  lines.push("");
}

lines.push(
  `-- Totals: ${hospitals.length} entities, ${seamCount} routing seams (${activeSeamCount} active), ${queueDefCount} queue definitions.`,
);
lines.push("");

writeFileSync(OUTPUT, lines.join("\n"));
console.log(
  `Wrote ${path.relative(REPO, OUTPUT)}: ${hospitals.length} entities, ` +
    `${activeSeamCount} active seams, ${queueDefCount} queue defs`,
);
